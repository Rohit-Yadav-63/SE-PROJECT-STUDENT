// Helper to determine status based on provided or current time string (HH:MM)
export const getClassStatus = (startTime, endTime, currentTimeStr) => {
  if (!currentTimeStr) return 'Upcoming';
  const [nowH, nowM] = currentTimeStr.split(':').map(Number);
  const [startH, startM] = startTime.split(':').map(Number);
  const [endH, endM] = endTime.split(':').map(Number);

  const nowMinutes = nowH * 60 + nowM;
  const startMinutes = startH * 60 + startM;
  const endMinutes = endH * 60 + endM;

  if (nowMinutes < startMinutes) {
    return 'Upcoming';
  } else if (nowMinutes >= startMinutes && nowMinutes <= endMinutes) {
    return 'Ongoing';
  } else {
    return 'Completed';
  }
};
